#!/usr/bin/env python3
"""Render docs/guide/cli-reference.md from `mysh help --json`.

    scripts/gen-cli-reference.py [PATH-TO-MYSH] > docs/guide/cli-reference.md

The command tree comes from clap through `mysh help --json`, so the
reference cannot drift from the binary. Prose about what the commands mean
lives in the other guide pages; this file is the exhaustive flag list.
"""

import json
import subprocess
import sys

BIN = sys.argv[1] if len(sys.argv) > 1 else "mysh"

# Options every HOST-taking command shares; rendered once at the top and
# elided from each command's table.
SHARED = {
    "port", "identity", "pin", "accept-new", "strict", "shell", "force-pty",
    "no-pty", "no-session", "attach", "local", "remote", "dynamic", "escape",
    "quiet", "env", "baked-only", "json", "json-stream", "plain", "timeout",
    "cwd", "no-ctl", "master", "hosts", "group", "verbose",
}


def tree():
    out = subprocess.run([BIN, "help", "--json"], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def arg_syntax(a):
    parts = []
    if a.get("short"):
        parts.append(f"-{a['short']}")
    if a.get("long"):
        parts.append(f"--{a['long']}")
    if a.get("positional") or not parts:
        name = (a.get("value_name") or a.get("name", "ARG")).upper()
        s = f"<{name}>" if a.get("required") else f"[{name}]"
        return f"`{s}{'...' if a.get('repeatable') else ''}`"
    s = ", ".join(parts)
    if a.get("takes_value"):
        s += f" <{(a.get('value_name') or a.get('name', 'VALUE')).upper()}>"
    if a.get("repeatable") and a.get("takes_value"):
        s += " (repeatable)"
    return f"`{s}`"


def shares_connect_opts(node):
    """Only commands that take a HOST carry the shared connection options;
    other commands (`serve`, `keygen`, ...) may reuse a name such as `--shell`
    with a different meaning and must keep it."""
    longs = {a.get("long") for a in node.get("args", [])}
    return {"pin", "accept-new", "identity", "port"} <= longs


def render_args(args, elide_shared):
    rows = []
    for a in args:
        if elide_shared and a.get("long") in SHARED:
            continue
        help_ = (a.get("help") or "").replace("\n", " ").replace("|", "\\|")
        default = a.get("default")
        if default not in (None, "", [], False, "0", "false"):
            help_ += f" (default `{default}`)"
        rows.append(f"| {arg_syntax(a)} | {help_} |")
    if not rows:
        return ""
    return "| option | meaning |\n| --- | --- |\n" + "\n".join(rows) + "\n"


def usage(node, path):
    pos = [a for a in node.get("args", []) if a.get("positional")]
    pos_s = " ".join(
        (f"<{(a.get('value_name') or a.get('name', 'ARG')).upper()}>" if a.get("required")
         else f"[{(a.get('value_name') or a.get('name', 'ARG')).upper()}]") + ("..." if a.get("repeatable") else "")
        for a in pos
    )
    return f"`{' '.join(path)} [OPTIONS] {pos_s}`".replace("  ", " ").replace(" `", "`")


def render(node, path, depth, elide_shared, out):
    name = " ".join(path)
    about = (node.get("about") or "").strip()
    out.append(f"{'#' * depth} `{name}`\n")
    if about:
        out.append(about + "\n")
    out.append(usage(node, path) + "\n")
    table = render_args(node.get("args", []), elide_shared and shares_connect_opts(node))
    if table:
        out.append(table)
    for sub in node.get("subcommands", []):
        if sub["command"] in ("help",):
            continue
        render(sub, path + [sub["command"]], min(depth + 1, 4), True, out)


def main():
    t = tree()
    out = [
        "# CLI reference\n",
        "Generated by `scripts/gen-cli-reference.py` from `mysh help --json`; "
        "do not edit by hand. See the other guide pages for what the commands "
        "mean and how they fit together.\n",
        "## Shared connection options\n",
        "Every command that takes a `HOST` accepts these (shown once here, "
        "elided from the tables below):\n",
    ]
    root = t
    shared_rows = [a for a in root.get("args", []) if a.get("long") in SHARED]
    out.append(render_args(shared_rows, False))
    out.append("## `mysh HOST [CMD...]`\n")
    out.append(
        "Bare form: `mysh HOST` lands at the meta prompt; `mysh HOST CMD...` runs "
        "`CMD` remotely and exits with its status. `HOST` is `host`, "
        "`host:port`, `[v6]:port`, a config alias, or `@NAME` for a connection "
        "accepted by `mysh accept`.\n"
    )
    for sub in root.get("subcommands", []):
        render(sub, ["mysh", sub["command"]], 2, True, out)
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
